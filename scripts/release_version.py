"""Set the release version everywhere: python3 scripts/release_version.py 0.2.1."""
import argparse
import json
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('version',nargs='?')
    args=parser.parse_args()
    if not args.version:
        print((ROOT/'VERSION').read_text().strip());return
    version=args.version
    if not re.fullmatch(r'\d+\.\d+\.\d+(?:-[a-zA-Z0-9.-]+)?',version):parser.error('Use a version such as 0.2.1')
    (ROOT/'VERSION').write_text(version+'\n')
    (ROOT/'backend/foxory/version.py').write_text('# Generated by scripts/release_version.py\n__version__ = '+repr(version)+'\n')
    (ROOT/'frontend/src/version.ts').write_text('// Generated by scripts/release_version.py\nexport const APP_VERSION = '+json.dumps(version)+';\n')
    p=ROOT/'backend/pyproject.toml';p.write_text(re.sub(r'^version = ".*"$',f'version = "{version}"',p.read_text(),count=1,flags=re.M))
    p=ROOT/'frontend/package.json';data=json.loads(p.read_text());data['version']=version;p.write_text(json.dumps(data,indent=2)+'\n')
    p=ROOT/'frontend/package-lock.json';data=json.loads(p.read_text());data['version']=version;data['packages']['']['version']=version;p.write_text(json.dumps(data,indent=2)+'\n')
    print('Release version:',version)

if __name__=='__main__':main()
